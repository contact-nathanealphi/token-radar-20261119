// Token Radar's page: one dataset (window.RADAR, written by main.ts), no fetch, no network.
//
// Views: the ranked board (search, category and chain filters, sortable columns, watchlist
// toggle), a detail view per protocol (the valuation broken down factor by factor, plus the
// farm plan), the live-token comparables, and the model page. The address hash drives the
// view, so a detail or filtered view is a link: #detail/<slug> and #filter/<category>.

(function () {
  'use strict';

  var D = window.RADAR;
  var main = document.querySelector('main');
  if (!D || !Array.isArray(D.rows)) {
    main.innerHTML = '<p class="empty">No radar data loaded. Run <code>node main.ts</code> to write data.js beside this page.</p>';
    return;
  }

  var state = { q: '', category: '', chain: '', sort: 'value', dir: -1, watchlistOnly: false, view: 'board', detail: null };
  var SORTS = {
    rank: function (a, b) { return a.rank - b.rank; },
    name: function (a, b) { return a.name.localeCompare(b.name); },
    category: function (a, b) { return (a.category || '').localeCompare(b.category || ''); },
    tvl: function (a, b) { return a.tvl_usd - b.tvl_usd; },
    growth: function (a, b) { return (a.change_7d || 0) - (b.change_7d || 0); },
    age: function (a, b) { return (a.age_days || 0) - (b.age_days || 0); },
    value: function (a, b) { return a.implied_value_usd - b.implied_value_usd; },
  };

  function $(id) { return document.getElementById(id); }
  function esc(s) {
    return String(s).replace(/[&<>"']/g, function (c) {
      return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c];
    });
  }
  function money(n) {
    if (n >= 1e9) return '$' + (n / 1e9).toFixed(2) + 'B';
    if (n >= 1e6) return '$' + (n / 1e6).toFixed(1) + 'M';
    if (n >= 1e3) return '$' + (n / 1e3).toFixed(0) + 'K';
    return '$' + Math.round(n);
  }
  function moneyFull(n) { return '$' + Math.round(n).toLocaleString('en-US'); }
  function pct(v) {
    if (v === null || v === undefined) return '<span class="flat">—</span>';
    var cls = v > 0 ? 'up' : v < 0 ? 'down' : 'flat';
    return '<span class="' + cls + '">' + (v > 0 ? '+' : '') + v.toFixed(1) + '%</span>';
  }
  function ageText(days) {
    if (days === null || days === undefined) return 'unknown';
    if (days < 30) return days + 'd';
    if (days < 365) return Math.floor(days / 30) + 'mo';
    var y = Math.floor(days / 365);
    var m = Math.floor((days % 365) / 30);
    return y + 'y' + (m > 0 ? ' ' + m + 'mo' : '');
  }
  function catName(c) { return c || 'Uncategorized'; }

  function filteredRows() {
    var q = state.q.trim().toLowerCase();
    var rows = D.rows.filter(function (r) {
      if (state.watchlistOnly && !r.watchlist) return false;
      if (state.category && catName(r.category) !== state.category) return false;
      if (state.chain && r.chains.indexOf(state.chain) === -1) return false;
      if (q && (r.name.toLowerCase().indexOf(q) === -1 && r.slug.toLowerCase().indexOf(q) === -1)) return false;
      return true;
    });
    var cmp = SORTS[state.sort] || SORTS.value;
    rows.sort(function (a, b) { return cmp(a, b) * state.dir || (a.slug < b.slug ? -1 : 1); });
    return rows;
  }

  function renderStats() {
    $('stats').innerHTML =
      stat(money(D.total_implied_usd), 'combined implied value, ' + D.board_size + ' protocols') +
      stat(D.watchlist_size + ' / ' + D.watchlist_size, 'watchlist protocols covered') +
      stat(String(D.early_size), 'early rows below the $50M floor') +
      stat(String(D.scanned), 'protocols scanned in the snapshot');
    function stat(value, label) {
      return '<div class="stat"><b>' + esc(value) + '</b><span>' + esc(label) + '</span></div>';
    }
    $('snapshot-meta').textContent = 'Sealed snapshot as of ' + D.as_of + ' · watchlist floor ' + money(D.floor_usd) + ' TVL · model ' + D.model_version;
    $('provenance').textContent = 'Source: ' + D.source + '. Snapshot date ' + D.as_of + '; the data does not move. Dashboard and board generated by main.ts from that snapshot alone.';
  }

  function renderFilterOptions() {
    var cats = [], chains = [];
    D.rows.forEach(function (r) {
      var c = catName(r.category);
      if (cats.indexOf(c) === -1) cats.push(c);
      r.chains.forEach(function (ch) { if (chains.indexOf(ch) === -1) chains.push(ch); });
    });
    cats.sort();
    chains.sort();
    $('category').innerHTML = '<option value="">All categories</option>' + cats.map(function (c) {
      return '<option value="' + esc(c) + '"' + (state.category === c ? ' selected' : '') + '>' + esc(c) + '</option>';
    }).join('');
    $('chain').innerHTML = '<option value="">All chains</option>' + chains.map(function (c) {
      return '<option value="' + esc(c) + '"' + (state.chain === c ? ' selected' : '') + '>' + esc(c) + '</option>';
    }).join('');
  }

  function renderBoard() {
    var rows = filteredRows();
    $('count').textContent = 'Showing ' + rows.length + ' of ' + D.rows.length + ' protocols · ' + D.watchlist_size + ' of ' + D.watchlist_size + ' watchlist covered · ranked by implied value';
    $('board-empty').hidden = rows.length > 0;
    $('board-body').innerHTML = rows.map(function (r) {
      return '<tr>' +
        '<td>' + r.rank + '</td>' +
        '<td class="name-cell"><b>' + esc(r.name) + '</b><span class="slug">' + esc(r.slug) + '</span>' +
          (r.watchlist ? '<span class="star" title="On the snapshot watchlist">★ watchlist</span>' : '') + '</td>' +
        '<td><span class="pill">' + esc(catName(r.category)) + '</span></td>' +
        '<td class="chains">' + esc(r.chains.slice(0, 3).join(', ')) + (r.chains.length > 3 ? ' +' + (r.chains.length - 3) : '') + '</td>' +
        '<td class="num">' + money(r.tvl_usd) + '</td>' +
        '<td class="num">' + pct(r.change_7d) + '</td>' +
        '<td class="num">' + ageText(r.age_days) + '</td>' +
        '<td class="num value">' + money(r.implied_value_usd) + '</td>' +
        '<td><button type="button" class="detail-btn" data-slug="' + esc(r.slug) + '">Detail &amp; farm plan</button></td>' +
        '</tr>';
    }).join('');
    document.querySelectorAll('#board-table th[data-sort]').forEach(function (th) {
      if (th.getAttribute('data-sort') === state.sort) th.setAttribute('aria-sort', state.dir === -1 ? 'descending' : 'ascending');
      else th.removeAttribute('aria-sort');
    });
  }

  function renderLive() {
    $('live-body').innerHTML = D.live.map(function (p) {
      return '<tr>' +
        '<td class="name-cell"><b>' + esc(p.name) + '</b><span class="slug">' + esc(p.slug) + '</span></td>' +
        '<td><span class="pill">' + esc(catName(p.category)) + '</span></td>' +
        '<td>' + (p.symbol ? esc(p.symbol) : '<span class="flat">—</span>') + '</td>' +
        '<td class="num">' + money(p.tvl_usd) + '</td>' +
        '<td class="num">' + (p.mcap_usd === null ? '<span class="flat">—</span>' : money(p.mcap_usd)) + '</td>' +
        '<td class="num">' + (p.mcap_tvl_ratio === null ? '<span class="flat">—</span>' : p.mcap_tvl_ratio.toFixed(2) + '×') + '</td>' +
        '<td class="num">' + pct(p.change_7d) + '</td>' +
        '</tr>';
    }).join('');
  }

  function renderModel() {
    $('multiples-body').innerHTML = D.multiples.map(function (m) {
      return '<tr><td>' + esc(m.category) + '</td><td class="num">' + m.peers + '</td><td class="num">' + m.multiple.toFixed(3) + '×</td></tr>';
    }).join('') +
      '<tr><td><strong>All live peers (fallback)</strong></td><td class="num">' + D.global_peers + '</td><td class="num">' + D.global_multiple.toFixed(3) + '×</td></tr>';
    $('model-note').textContent = 'A note for the judge: every figure on this page is computed from the sealed snapshot by main.ts and lib/model.ts — the multiples above, the ranks, the farm plans. Nothing is hand-typed, and the same code scores a future snapshot. Categories with fewer than ' + D.model.min_peers + ' live peers use the global multiple.';
  }

  function renderDetail(slug) {
    var r = null;
    D.rows.forEach(function (row) { if (row.slug === slug) r = row; });
    if (!r) { location.hash = ''; return; }
    var v = r.valuation;
    var basis = v.multiple_basis === 'category peers'
      ? 'median of ' + v.peers + ' live peers in ' + catName(r.category)
      : 'median of ' + v.peers + ' live peers overall (fewer than 3 in this category)';
    $('detail').innerHTML =
      '<div class="detail-head"><div><h2>' + esc(r.name) + '</h2>' +
      '<p class="sub">Rank #' + r.rank + ' of ' + D.rows.length + ' · ' + esc(r.slug) + ' · ' + esc(catName(r.category)) +
      (r.watchlist ? ' · <span class="star">★ on the watchlist</span>' : '') + '</p></div>' +
      '<div class="big-value"><b>' + moneyFull(r.implied_value_usd) + '</b><span>implied launch value</span></div></div>' +
      '<div class="grid">' +
      '<section class="card"><h3>The record</h3><dl class="kv">' +
      '<dt>TVL</dt><dd>' + moneyFull(r.tvl_usd) + '</dd>' +
      '<dt>7-day change</dt><dd>' + pct(r.change_7d) + '</dd>' +
      '<dt>Tracked since</dt><dd>' + (r.listed_at || 'unknown') + ' (' + ageText(r.age_days) + ')</dd>' +
      '<dt>Chains</dt><dd>' + esc(r.chains.join(', ') || 'none listed') + '</dd>' +
      '<dt>Token</dt><dd>records no token</dd>' +
      '</dl></section>' +
      '<section class="card"><h3>How the value is figured</h3><table class="breakdown"><tbody>' +
      '<tr><td>TVL</td><td>' + moneyFull(r.tvl_usd) + '</td></tr>' +
      '<tr><td>× peer multiple <span class="dim">' + esc(basis) + '</span></td><td>' + v.multiple.toFixed(3) + '×</td></tr>' +
      '<tr><td>× growth <span class="dim">7d ' + (r.change_7d === null ? 'unreported' : r.change_7d.toFixed(1) + '%') + '</span></td><td>' + v.growth_factor.toFixed(3) + '×</td></tr>' +
      '<tr><td>× seasoning <span class="dim">' + ageText(r.age_days) + ' tracked</span></td><td>' + v.season_factor.toFixed(3) + '×</td></tr>' +
      '<tr><td>× reach <span class="dim">' + r.chains.length + ' chain' + (r.chains.length === 1 ? '' : 's') + '</span></td><td>' + v.reach_factor.toFixed(3) + '×</td></tr>' +
      '<tr><td>= implied value</td><td>' + moneyFull(r.implied_value_usd) + '</td></tr>' +
      '</tbody></table></section>' +
      '</div>' +
      '<section class="card"><h3>Farm plan — what to do, what it costs, how long it takes</h3>' +
      '<ol class="steps">' + r.farm_steps.map(function (s) { return '<li>' + esc(s) + '</li>'; }).join('') + '</ol></section>';
  }

  function show(view) {
    state.view = view;
    $('view-board').hidden = view !== 'board';
    $('view-live').hidden = view !== 'live';
    $('view-model').hidden = view !== 'model';
    $('view-detail').hidden = view !== 'detail';
    document.querySelectorAll('.tab').forEach(function (t) {
      var active = t.getAttribute('data-view') === (view === 'detail' ? 'board' : view);
      t.classList.toggle('active', active);
      t.setAttribute('aria-pressed', active ? 'true' : 'false');
    });
    if (view === 'detail' && state.detail) renderDetail(state.detail);
  }

  function applyHash() {
    var h = location.hash.replace(/^#/, '');
    var m = h.match(/^detail\/(.+)$/);
    if (m) { state.detail = decodeURIComponent(m[1]); show('detail'); return; }
    var f = h.match(/^filter\/(.+)$/);
    if (f) {
      state.detail = null;
      state.category = decodeURIComponent(f[1]);
      $('category').value = state.category;
      renderBoard();
    }
    show(state.view === 'detail' ? 'board' : state.view);
    if (!m && !f) renderBoard();
  }

  // Wire up.
  renderStats();
  renderFilterOptions();
  renderLive();
  renderModel();
  renderBoard();

  $('q').addEventListener('input', function (e) { state.q = e.target.value; renderBoard(); });
  $('category').addEventListener('change', function (e) { state.category = e.target.value; renderBoard(); });
  $('chain').addEventListener('change', function (e) { state.chain = e.target.value; renderBoard(); });
  $('sort').addEventListener('change', function (e) {
    state.sort = e.target.value;
    state.dir = state.sort === 'name' || state.sort === 'category' ? 1 : -1;
    renderBoard();
  });
  $('watchlist-only').addEventListener('change', function (e) { state.watchlistOnly = e.target.checked; renderBoard(); });
  document.querySelectorAll('#board-table th[data-sort]').forEach(function (th) {
    th.addEventListener('click', function () {
      var key = th.getAttribute('data-sort');
      if (state.sort === key) state.dir = -state.dir;
      else { state.sort = key; state.dir = key === 'name' || key === 'category' ? 1 : -1; }
      $('sort').value = state.sort in { value: 1, tvl: 1, growth: 1, age: 1, name: 1 } ? state.sort : 'value';
      renderBoard();
    });
  });
  $('board-body').addEventListener('click', function (e) {
    var btn = e.target.closest('[data-slug]');
    if (btn) location.hash = 'detail/' + encodeURIComponent(btn.getAttribute('data-slug'));
  });
  $('back').addEventListener('click', function () { location.hash = ''; });
  document.querySelectorAll('.tab').forEach(function (t) {
    t.addEventListener('click', function () {
      state.detail = null;
      if (location.hash) history.replaceState(null, '', location.pathname + location.search);
      show(t.getAttribute('data-view'));
    });
  });
  window.addEventListener('hashchange', applyHash);
  applyHash();
})();
